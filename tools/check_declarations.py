"""Read the real example output with Kconfiglib, not our own config parser."""
import argparse, pathlib, subprocess, tempfile, os
import kconfiglib
from cases import cases
p=argparse.ArgumentParser();p.add_argument('--moon',default='moon');p.add_argument('--target',default='js');a=p.parse_args()
root=pathlib.Path(__file__).resolve().parents[1]
r=subprocess.run([a.moon,'run','examples/declarations','--target',a.target],cwd=root,stdout=subprocess.PIPE,check=True)
output=r.stdout.decode('utf8');assert output.startswith('# Generated by MoonKconfig;')
label,files,fragment=next(c for c in cases() if c[0]=='multifile-shared-0-1')
with tempfile.TemporaryDirectory() as temp:
 folder=pathlib.Path(temp)
 for name,text in files.items():
  f=folder/name;f.parent.mkdir(parents=True,exist_ok=True);f.write_text(text,encoding='utf8')
 old=os.environ.get('srctree');os.environ['srctree']=str(folder)
 try:
  ref=kconfiglib.Kconfig(str(folder/'Kconfig'),warn_to_stderr=False)
  config=folder/'.config';config.write_text(fragment,encoding='utf8');ref.load_config(str(config))
  expected={s.name:s.str_value for s in ref.unique_defined_syms}
  config.write_text(output,encoding='utf8');ref.load_config(str(config))
  assert {s.name:s.str_value for s in ref.unique_defined_syms}==expected
  assert not ref.warnings,ref.warnings
 finally:
  if old is None:os.environ.pop('srctree',None)
  else:os.environ['srctree']=old
print('Cross-file exported .config independently consumed: LEFT=n RIGHT=y SHARED=22')
